import { describe, expect, test } from "bun:test";
import { loadIndexConfig } from "../src/config";
import {
  checkContent,
  classifyPath,
  containsSecret,
  DEFAULT_INDEX_LIMITS,
  type ExclusionReason,
  isSafeRepoPath,
  validateLimits,
} from "../src/indexing/policy";

const encode = (text: string) => new TextEncoder().encode(text);

describe("path eligibility", () => {
  test.each([
    ["src/index.ts", "typescript"],
    ["test/app.test.tsx", "typescript"],
    ["scripts/build.mjs", "javascript"],
    ["docs/README.md", "markdown"],
    ["package.json", "json"],
    [".github/workflows/check.yml", "yaml"],
    ["tools/gen.py", "python"],
    ["cmd/main.go", "go"],
    ["Dockerfile", "dockerfile"],
    [".gitignore", "text"],
    ["LICENSE", "text"],
  ])("indexes %s as %s", (path, language) => {
    expect(classifyPath(path)).toEqual({ eligible: true, language });
  });

  test.each([
    [".env", "secret_path"],
    ["config/.env.production", "secret_path"],
    ["deploy/prod.env", "secret_path"],
    ["certs/server.pem", "secret_path"],
    ["keys/signing.key", "secret_path"],
    ["home/.ssh/id_ed25519", "secret_path"],
    ["home/.ssh/id_rsa.pub", "secret_path"],
    [".npmrc", "secret_path"],
    ["gcp/credentials.json", "secret_path"],
    ["infra/terraform.tfstate", "secret_path"],
    ["node_modules/react/index.js", "dependency"],
    ["packages/app/node_modules/x/a.ts", "dependency"],
    ["vendor/github.com/x/y.go", "dependency"],
    ["dist/index.js", "generated"],
    ["packages/web/build/app.js", "generated"],
    ["coverage/lcov.info", "generated"],
    ["bun.lock", "generated"],
    ["package-lock.json", "generated"],
    ["public/app.min.js", "generated"],
    ["public/app.js.map", "generated"],
    ["assets/logo.png", "binary"],
    ["fonts/inter.woff2", "binary"],
    ["data/looky.sqlite", "binary"],
    ["../escape.ts", "unsafe_path"],
    ["src/../../escape.ts", "unsafe_path"],
    ["/etc/passwd", "unsafe_path"],
    [".git/config", "unsafe_path"],
    ["sub/.GIT/hooks/pre-commit", "unsafe_path"],
    ["src/a\nb.ts", "unsafe_path"],
    ["src//a.ts", "unsafe_path"],
  ])("excludes %s as %s", (path, reason) => {
    expect(classifyPath(path)).toEqual({ eligible: false, reason: reason as ExclusionReason });
  });

  test("safe paths are relative and normalized", () => {
    expect(isSafeRepoPath("a/b/c.ts")).toBe(true);
    expect(isSafeRepoPath("")).toBe(false);
    expect(isSafeRepoPath("./a.ts")).toBe(false);
    expect(isSafeRepoPath("a\\b.ts")).toBe(false);
  });
});

describe("content eligibility", () => {
  const limits = { ...DEFAULT_INDEX_LIMITS, maxLineBytes: 100, chunkBytes: 200 };

  test("keeps exact text, including BOM and CRLF", () => {
    const text = "﻿line one\r\nline two\r\n";
    expect(checkContent(encode(text), limits)).toEqual({ eligible: true, text });
  });

  test.each([
    ["NUL bytes", new Uint8Array([104, 105, 0, 33]), "binary"],
    ["invalid UTF-8", new Uint8Array([0xff, 0xfe, 0x41]), "binary"],
    ["whitespace only", encode("  \n\n"), "empty"],
    ["a very long line", encode(`const x = "${"a".repeat(200)}";\n`), "long_lines"],
    ["a generated header", encode("// @generated by protoc\nexport const a = 1;\n"), "generated"],
    ["a DO NOT EDIT header", encode("# Code generated. DO NOT EDIT.\nx\n"), "generated"],
  ])("excludes %s", (_name, bytes, reason) => {
    expect(checkContent(bytes, limits)).toEqual({
      eligible: false,
      reason: reason as ExclusionReason,
    });
  });

  test.each([
    ["a private key block", "-----BEGIN RSA PRIVATE KEY-----\nMIIE\n-----END RSA PRIVATE KEY-----"],
    ["an OpenSSH key", "-----BEGIN OPENSSH PRIVATE KEY-----"],
    ["an AWS access key id", 'const id = "AKIAIOSFODNN7EXAMPLE";'],
    ["a GitHub token", `token = "ghp_${"a1B2".repeat(9)}"`],
    ["a Slack token", "xoxb-1234567890-abcdefghij"],
    ["an API secret key", `OPENAI_KEY=sk-proj-${"x7".repeat(20)}`],
    ["a Google API key", `key: AIza${"Sy".repeat(17)}A`],
    ["a credentialed URL", "DATABASE_URL=postgres://app:hunter2secret@db.internal:5432/app"],
  ])("detects %s anywhere in the file", (_name, secret) => {
    const text = `export const ok = 1;\n${secret}\n`;
    expect(containsSecret(text)).toBe(true);
    expect(checkContent(encode(text), limits)).toEqual({
      eligible: false,
      reason: "secret_content",
    });
  });

  test("allows placeholder credentials in example URLs", () => {
    expect(containsSecret("postgres://user:password@localhost:5432/db")).toBe(false);
    expect(containsSecret("postgres://user:${DB_PASSWORD}@localhost/db")).toBe(false);
    expect(containsSecret("https://example.com/path?q=1")).toBe(false);
  });
});

describe("index limits", () => {
  test("defaults are valid and the environment can override them", () => {
    expect(() => validateLimits(DEFAULT_INDEX_LIMITS)).not.toThrow();
    const config = loadIndexConfig({
      LOOKY_INDEX_MAX_FILE_BYTES: "2048",
      LOOKY_INDEX_CHUNK_OVERLAP_LINES: "0",
      LOOKY_INDEX_MAX_CONCURRENT_BUILDS: "2",
    });
    expect(config.limits.maxFileBytes).toBe(2048);
    expect(config.limits.chunkOverlapLines).toBe(0);
    expect(config.maxConcurrentBuilds).toBe(2);
  });

  test("rejects inconsistent or invalid limits", () => {
    expect(() => loadIndexConfig({ LOOKY_INDEX_MAX_FILES: "0" })).toThrow("positive integer");
    expect(() => loadIndexConfig({ LOOKY_INDEX_CHUNK_BYTES: "10" })).toThrow("maxLineBytes");
    expect(() => loadIndexConfig({ LOOKY_INDEX_CHUNK_OVERLAP_LINES: "80" })).toThrow(
      "below chunkLines",
    );
  });
});
