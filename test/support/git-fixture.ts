import { mkdirSync, symlinkSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

export function git(directory: string, ...args: string[]): string {
  const result = Bun.spawnSync(["git", "-C", directory, ...args], {
    env: {
      ...process.env,
      GIT_AUTHOR_NAME: "Looky Test",
      GIT_AUTHOR_EMAIL: "test@example.invalid",
      GIT_COMMITTER_NAME: "Looky Test",
      GIT_COMMITTER_EMAIL: "test@example.invalid",
    },
  });
  if (result.exitCode !== 0) throw new Error(result.stderr.toString());
  return result.stdout.toString().trim();
}

export function initRepo(directory: string): void {
  git(directory, "init", "--quiet", "--initial-branch=main");
  git(directory, "config", "commit.gpgsign", "false");
}

export function write(repo: string, path: string | Buffer, content: string | Uint8Array): void {
  const full =
    typeof path === "string" ? join(repo, path) : Buffer.concat([Buffer.from(`${repo}/`), path]);
  mkdirSync(dirname(full.toString()), { recursive: true });
  writeFileSync(full, content);
}

export function commitAll(repo: string, message: string): string {
  git(repo, "add", "--all");
  git(repo, "commit", "--quiet", "--allow-empty", "-m", message);
  return git(repo, "rev-parse", "HEAD");
}

